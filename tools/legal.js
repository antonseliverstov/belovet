// Политика обработки персональных данных и согласие (152-ФЗ). Черновик: перед запуском проверить юристу.
// Данные оператора задаются в OPERATOR в tools/build.js. Пустые поля выводятся как [заполнить] и не дают включить LAUNCH.

module.exports = function legal(ctx) {
  const { SITE, UI, ogTags, iconTags, esc, OPERATOR, LEGAL_DATE, FORMS_ON = true, METRIKA_ID = '' } = ctx;
  const O = OPERATOR;
  const f = (v, hint) => v ? esc(v) : `<mark class="todo">[${hint}]</mark>`;
  const who = `${f(O.status, 'статус: ИП или самозанятый')} ${f(O.name, 'ФИО полностью')}`;
  const ids = [O.inn ? `ИНН ${esc(O.inn)}` : `<mark class="todo">[ИНН]</mark>`, O.ogrnip ? `ОГРНИП ${esc(O.ogrnip)}` : ''].filter(Boolean).join(', ');
  const missing = FORMS_ON ? ['name', 'status', 'inn', 'address'].filter(k => !O[k]) : [];

  const sec = (id, h, body) => `    <h2 id="${id}">${h}</h2>\n${body}`;
  const p = t => `    <p>${t}</p>`;
  const ul = items => `    <ul>\n${items.map(i => `      <li>${i}</li>`).join('\n')}\n    </ul>`;

  function page({ file, title, h1, lead, sub, photo, body }) {
    const url = SITE + file;
    const desc = lead;
    return `${UI.head({ title, desc, url, prefix: '', type: 'website', ogTags: ogTags(title, desc, url, 'website'), iconTags: iconTags('') })}
<body>
<main>
${UI.pageHero('', [['Главная', 'index.html'], [h1, '']], h1, lead, null, { sub, lw: 760, photo })}
<section class="fx" style="--bg:#fff">
  <article class="sx prose">
    ${UI.doodle('', 'p01-paws.png', '--x:1260;--y:110;--w:253')}
${missing.length ? `    <aside class="prose-note coral"><b>Черновик</b><p>Текст подготовлен по 152-ФЗ «О персональных данных» и требует проверки юристом. Поля, выделенные пунктиром, нужно заполнить данными оператора.</p></aside>\n` : ''}${body}
    <p class="t" style="--fs:20;--lh:28">Редакция от ${esc(LEGAL_DATE)}.</p>
  </article>
</section>
</main>
${UI.footer('')}
</body>
</html>
`;
  }

  // Формы выключены: сайт не собирает данные, политика короткая и без полей оператора
  if (!FORMS_ON) {
    const short = page({
      file: 'privacy.html',
      title: 'Политика конфиденциальности | beloVET',
      h1: 'Политика конфиденциальности',
      lead: 'Сайт beloVET не собирает персональные данные: на нём нет форм заявок и регистрации. Записаться на приём можно по телефону.',
      sub: 'Персональные данные',
      photo: { name: 'pinscher-squint', x: 1165, y: 554, w: 428 },
      body: [
        sec('data', 'Какие данные собирает сайт', [
          p('Сайт не содержит форм заявок, регистрации и подписки и не запрашивает имя, телефон или другие персональные данные.'),
          p(`Записаться на приём или задать вопрос врачу можно по телефону ${esc(O.phone)} или по электронной почте <a href="mailto:${esc(O.email)}">${esc(O.email)}</a>. Данные, которые вы сообщаете при звонке или в письме, используются только для ответа на ваше обращение и записи питомца на приём и не передаются третьим лицам.`)
        ].join('\n')),
        sec('cookie', 'Файлы cookie', [
          p('Сайт сохраняет в браузере отметку о том, что вы закрыли уведомление о cookie, чтобы не показывать его повторно.'),
          METRIKA_ID
            ? p('Для обезличенной статистики посещений подключён сервис Яндекс Метрика (ООО «Яндекс»): он получает сведения о посещённых страницах, источнике перехода, типе устройства и браузера. Отключить cookie можно в настройках браузера или с помощью <a href="https://yandex.ru/support/metrica/general/opt-out.html" target="_blank" rel="noopener">блокировщика Яндекс Метрики</a>.')
            : p('Сервисы веб-аналитики на сайте не подключены. Если они появятся, это будет указано здесь.')
        ].join('\n')),
        sec('changes', 'Изменения', p('Если на сайте появятся формы для заявок, политика будет дополнена до их подключения.'))
      ].join('\n')
    });
    return { privacy: short, consent: '', missing };
  }

  const privacy = page({
    file: 'privacy.html',
    title: 'Политика конфиденциальности | beloVET',
    h1: 'Политика конфиденциальности',
    lead: 'Как beloVET обрабатывает персональные данные из форм записи и вопросов врачу: какие данные собираем, зачем, сколько храним и как их удалить.',
    sub: 'Персональные данные',
    photo: { name: 'pinscher-squint', x: 1165, y: 554, w: 428 },
    body: [
      sec('operator', '1. Кто обрабатывает данные', [
        p(`Оператор персональных данных — ${who}, ${ids}. Адрес для обращений: ${f(O.address, 'почтовый адрес')}. Электронная почта: <a href="mailto:${esc(O.email)}">${esc(O.email)}</a>, телефон: ${esc(O.phone)}.`),
        p(`Политика действует для сайта ${esc(SITE.replace(/\/$/, ''))} и всех его страниц. Отправляя форму на сайте, вы подтверждаете, что ознакомились с ней.`)
      ].join('\n')),
      sec('data', '2. Какие данные мы получаем', [
        ul([
          'имя и номер телефона — из форм записи, экстренной записи и вопроса врачу',
          'кличку питомца и описание ситуации, если вы их указали',
          'файлы, которые вы прикрепили к заявке: фото, снимки, выписки',
          'технические данные: адрес страницы, с которой отправлена заявка, время отправки',
          'обезличенные данные о посещении сайта через файлы cookie и Яндекс Метрику (подробнее — в разделе 7)'
        ]),
        p('Мы не просим и не обрабатываем специальные категории персональных данных и биометрию. Пожалуйста, не указывайте в заявке сведения, которые не нужны для записи питомца на приём.')
      ].join('\n')),
      sec('purpose', '3. Зачем мы обрабатываем данные', [
        ul([
          'чтобы связаться с вами по заявке: перезвонить, записать питомца на приём или операцию',
          'чтобы ответить на вопрос о здоровье питомца',
          'чтобы врач заранее оценил ситуацию по присланным материалам',
          'чтобы улучшать работу сайта на основе обезличенной статистики посещений'
        ]),
        p('Правовое основание — ваше согласие на обработку персональных данных (статья 6 и статья 9 152-ФЗ). Мы не используем данные для рассылок и не передаём их для рекламы.')
      ].join('\n')),
      sec('how', '4. Как мы обрабатываем данные', [
        p('Обработка — сбор, запись, систематизация, хранение, уточнение, использование, удаление и уничтожение данных. Обработка ведётся с использованием средств автоматизации и без них.'),
        p('Заявка с сайта передаётся через облачную функцию на серверах в России и поступает врачу на электронную почту и в мессенджер Telegram. Для этого привлекаются:'),
        ul([
          'ООО «Яндекс.Облако» — облачная функция приёма заявок, серверы в России',
          'ООО «Таймвэб» — электронная почта домена belovet.ru, серверы в России',
          '<mark class="todo">[Проверить юристу]</mark> Telegram — мессенджер, серверы которого находятся за пределами России. Отправка заявки в Telegram является трансграничной передачей: до её начала оператор уведомляет Роскомнадзор, а в согласии это указано отдельно'
        ]),
        p('Доступ к заявкам есть только у врача. Мы принимаем организационные и технические меры для защиты данных: передача по защищённому соединению (HTTPS), доступ к почте и мессенджеру защищён паролем, данные не публикуются.')
      ].join('\n')),
      sec('storage', '5. Сколько хранятся данные', [
        p('Данные заявки хранятся не дольше, чем нужно для её обработки и последующего лечения питомца, и не дольше 3 лет с момента последнего обращения, если иной срок не установлен законом. По истечении срока или после отзыва согласия данные удаляются в течение 30 дней.')
      ].join('\n')),
      sec('rights', '6. Ваши права', [
        ul([
          'узнать, какие ваши данные мы обрабатываем и зачем',
          'потребовать уточнить, заблокировать или удалить данные',
          'отозвать согласие на обработку',
          'обжаловать действия оператора в Роскомнадзоре или в суде'
        ]),
        p(`Чтобы воспользоваться правами, напишите на <a href="mailto:${esc(O.email)}">${esc(O.email)}</a> или на почтовый адрес оператора. Мы ответим в течение 10 рабочих дней.`)
      ].join('\n')),
      sec('cookie', '7. Файлы cookie и Яндекс Метрика', [
        p('Сайт использует файлы cookie — небольшие файлы, которые браузер сохраняет на устройстве. Они нужны, чтобы сайт работал корректно (например, запоминал, что вы закрыли уведомление), и чтобы собирать обезличенную статистику посещений.'),
        p('Для статистики подключён сервис Яндекс Метрика (ООО «Яндекс»). Он получает сведения о посещённых страницах, источнике перехода, типе устройства и браузера, обезличенный идентификатор посетителя, а также записывает действия на странице (Вебвизор) без ввода данных в поля форм. Метрика используется только для анализа и улучшения сайта.'),
        p('Вы можете отключить cookie в настройках браузера или установить <a href="https://yandex.ru/support/metrica/general/opt-out.html" target="_blank" rel="noopener">блокировщик Яндекс Метрики</a>. Сайт продолжит работать.')
      ].join('\n')),
      sec('changes', '8. Изменения политики', [
        p('Мы можем обновлять политику. Новая редакция действует с момента публикации на этой странице. Текст согласия на обработку персональных данных опубликован <a href="consent.html">отдельно</a>.')
      ].join('\n'))
    ].join('\n')
  });

  const consent = page({
    file: 'consent.html',
    title: 'Согласие на обработку персональных данных | beloVET',
    h1: 'Согласие на обработку персональных данных',
    lead: 'Текст согласия, которое вы даёте, отмечая галочку в форме записи, экстренной записи или вопроса врачу на сайте beloVET.',
    sub: 'Персональные данные',
    photo: { name: 'pinscher-squint', x: 1165, y: 554, w: 428 },
    body: [
      p(`Отправляя форму на сайте ${esc(SITE.replace(/\/$/, ''))}, я свободно, своей волей и в своём интересе даю согласие оператору — ${who}, ${ids}, адрес: ${f(O.address, 'почтовый адрес')} — на обработку моих персональных данных на следующих условиях.`),
      sec('c-data', 'Какие данные', ul(['имя', 'номер телефона', 'кличка питомца и описание ситуации, если я их указал', 'прикреплённые к заявке файлы'])),
      sec('c-purpose', 'Цель', p('Связаться со мной по заявке, записать питомца на приём или операцию, ответить на вопрос о его здоровье.')),
      sec('c-actions', 'Действия с данными', p('Сбор, запись, систематизация, накопление, хранение, уточнение, извлечение, использование, передача (предоставление, доступ) лицам, указанным в политике конфиденциальности, блокирование, удаление, уничтожение — с использованием средств автоматизации и без них.')),
      sec('c-transfer', 'Передача', p('Я согласен, что заявка передаётся через облачную функцию ООО «Яндекс.Облако» и поступает оператору на электронную почту (ООО «Таймвэб») и в мессенджер Telegram, в том числе с трансграничной передачей данных в связи с использованием Telegram. <mark class="todo">[Проверить юристу]</mark>')),
      sec('c-term', 'Срок и отзыв', p(`Согласие действует 3 года с момента отправки формы или до его отзыва. Я могу отозвать согласие, направив письмо на <a href="mailto:${esc(O.email)}">${esc(O.email)}</a> или на почтовый адрес оператора. После отзыва данные удаляются в течение 30 дней.`)),
      p('Я ознакомлен с <a href="privacy.html">политикой конфиденциальности</a>.')
    ].join('\n')
  });

  return { privacy, consent, missing };
};
